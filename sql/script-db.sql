CREATE DATABASE EXPERT_SYSTEM_PHONES;
USE EXPERT_SYSTEM_PHONES;

-- BASE DE DATOS TRANSACCIONAL
CREATE TABLE CLIENTE (
    ID_CLIENTE INT PRIMARY KEY AUTO_INCREMENT,
    NOMBRES VARCHAR(255),
    APELLIDOS VARCHAR(255),
    CORREO VARCHAR(255)
); 

CREATE TABLE RECOMENDACION (
    ID_RECOMENDACION INT PRIMARY KEY AUTO_INCREMENT,
    ID_CLIENTE INT,
    FECHA DATE,
    FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE)
);

CREATE TABLE PREGUNTAS (
    ID_PREGUNTAS INT PRIMARY KEY AUTO_INCREMENT,
    PREGUNTA VARCHAR(255)
);

CREATE TABLE RESPUESTAS (
    ID_RESPUESTAS INT PRIMARY KEY AUTO_INCREMENT,
    ID_PREGUNTAS INT,
    RESPUESTA VARCHAR(255),
    FOREIGN KEY (ID_PREGUNTAS) REFERENCES PREGUNTAS(ID_PREGUNTAS)
);


-- PENDIENTE!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!!
CREATE TABLE HIPOTESIS_RECOMENDACION (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    OPCIONES_ID INT,
    RECOMENDACIONES_ID INT,
    FOREIGN KEY (OPCIONES_ID) REFERENCES OPCIONES(ID),
    FOREIGN KEY (RECOMENDACIONES_ID) REFERENCES RECOMENDACION(ID_RECOMENDACION)
);

-- BASE DE DATOS DE CONOCIMIENTO
CREATE TABLE HECHOS (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    FILTRO VARCHAR(255)
);

CREATE TABLE OPCIONES (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    NOMBRE VARCHAR(255),
    PROPOSITO VARCHAR(255),
    PRESUPUESTO VARCHAR(255),
    ALMACENAMIENTO VARCHAR(255),
    RAM VARCHAR(255),
    MEGAPIXELES VARCHAR(255),
    BATERIA VARCHAR(255)
);

CREATE TABLE HECHOSXOPCIONES (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    HECHOS_ID INT,
    OPCIONES_ID INT,
    FOREIGN KEY (HECHOS_ID) REFERENCES HECHOS(ID),
    FOREIGN KEY (OPCIONES_ID) REFERENCES OPCIONES(ID)
); 

