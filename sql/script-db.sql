VALUES (NOMBRE, PROPOSITO, PRESUPUESTO, ALMACENAMIENTO, RAM, MEGAPIXELES, BATERIA);
SET ID_NUEVO_OPCIONES = LAST_INSERT_ID();

INSERT INTO HECHOSXOPCIONES (HECHOS_ID, OPCIONES_ID) VALUES (ID_NUEVO_HECHOS, ID_NUEVO_OPCIONES);
END //
