DECLARE ID_NUEVO_HECHOS INT;
DECLARE ID_NUEVO_OPCIONES INT;

INSERT INTO HECHOS (FILTRO) VALUES (FILTRO);
SET ID_NUEVO_HECHOS = LAST_INSERT_ID();

