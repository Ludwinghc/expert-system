 CREATE PROCEDURE REGISTRO_HECHOS_OPCIONES(
 IN FILTRO VARCHAR (255),
 IN NOMBRE VARCHAR(255),
 IN PROPOSITO VARCHAR(255),
 IN PRESUPUESTO VARCHAR(255),
 IN ALMACENAMIENTO VARCHAR(255),
